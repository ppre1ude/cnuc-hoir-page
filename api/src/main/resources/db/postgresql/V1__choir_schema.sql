CREATE TABLE member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_member PRIMARY KEY,
    email VARCHAR(320) NOT NULL CONSTRAINT uq_member_email UNIQUE,
    name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255),
    status VARCHAR(32) NOT NULL,
    member_type VARCHAR(16),
    admin BOOLEAN NOT NULL DEFAULT FALSE,
    auth_version BIGINT NOT NULL DEFAULT 0,
    email_verified_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE auth_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_auth_token PRIMARY KEY,
    member_id BIGINT NOT NULL CONSTRAINT fk_auth_token_member REFERENCES member (id),
    purpose VARCHAR(32) NOT NULL,
    token_hash VARCHAR(64) NOT NULL CONSTRAINT uq_auth_token_hash UNIQUE,
    expires_at TIMESTAMP(6) NOT NULL,
    used_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_auth_token_member_purpose ON auth_token (member_id, purpose);
CREATE INDEX ix_auth_token_expires_at ON auth_token (expires_at);

CREATE TABLE spring_session (
    primary_id CHAR(36) NOT NULL CONSTRAINT spring_session_pk PRIMARY KEY,
    session_id CHAR(36) NOT NULL,
    creation_time BIGINT NOT NULL,
    last_access_time BIGINT NOT NULL,
    max_inactive_interval INTEGER NOT NULL,
    expiry_time BIGINT NOT NULL,
    principal_name VARCHAR(100)
);
CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36) NOT NULL CONSTRAINT spring_session_attributes_fk
        REFERENCES spring_session (primary_id) ON DELETE CASCADE,
    attribute_name VARCHAR(200) NOT NULL,
    attribute_bytes BYTEA NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name)
);

CREATE TABLE auth_attempt (
    kind VARCHAR(32) NOT NULL,
    identity_hash VARCHAR(64) NOT NULL,
    window_start TIMESTAMP(6) NOT NULL,
    attempt_count INTEGER NOT NULL,
    CONSTRAINT pk_auth_attempt PRIMARY KEY (kind, identity_hash)
);

CREATE TABLE auth_mail_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_auth_mail_outbox PRIMARY KEY,
    member_id BIGINT NOT NULL CONSTRAINT fk_auth_mail_outbox_member REFERENCES member (id),
    purpose VARCHAR(32) NOT NULL,
    requested_at TIMESTAMP(6) NOT NULL,
    next_attempt_at TIMESTAMP(6) NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    completed_at TIMESTAMP(6),
    CONSTRAINT uq_auth_mail_outbox_member_purpose UNIQUE (member_id, purpose)
);
CREATE INDEX ix_auth_mail_outbox_due ON auth_mail_outbox (completed_at, next_attempt_at);

CREATE TABLE admin_action_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_admin_action_log PRIMARY KEY,
    actor_member_id BIGINT NOT NULL CONSTRAINT fk_admin_action_actor REFERENCES member (id),
    target_member_id BIGINT NOT NULL CONSTRAINT fk_admin_action_target REFERENCES member (id),
    action VARCHAR(32) NOT NULL,
    previous_status VARCHAR(32) NOT NULL,
    new_status VARCHAR(32) NOT NULL,
    reason VARCHAR(500),
    acted_at TIMESTAMP(6) NOT NULL,
    event_id BIGINT
);
CREATE INDEX ix_admin_action_target ON admin_action_log (target_member_id, acted_at);

CREATE TABLE notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    author_member_id BIGINT NOT NULL CONSTRAINT fk_notice_author REFERENCES member (id),
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    published_at TIMESTAMP(6)
);
CREATE INDEX idx_notice_published ON notice (published, published_at DESC, id DESC);

CREATE TABLE event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    start_at TIMESTAMP(6) NOT NULL,
    end_at TIMESTAMP(6) NOT NULL,
    ob_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    public_visible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_event_dates ON event (start_at, end_at, id);
ALTER TABLE admin_action_log ADD CONSTRAINT fk_admin_action_event FOREIGN KEY (event_id) REFERENCES event (id);

CREATE TABLE check_in_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL CONSTRAINT fk_check_in_session_event REFERENCES event (id),
    opened_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    closed_at TIMESTAMP(6),
    qr_token_hash VARCHAR(64) NOT NULL,
    code_hash VARCHAR(64) NOT NULL
);
CREATE UNIQUE INDEX uq_check_in_session_active_event ON check_in_session (event_id) WHERE closed_at IS NULL;
CREATE INDEX ix_check_in_session_event ON check_in_session (event_id, id);

CREATE TABLE attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL CONSTRAINT fk_attendance_event REFERENCES event (id),
    member_id BIGINT NOT NULL CONSTRAINT fk_attendance_member REFERENCES member (id),
    status VARCHAR(16) NOT NULL,
    checked_in_at TIMESTAMP(6),
    corrected_at TIMESTAMP(6),
    CONSTRAINT uq_attendance_event_member UNIQUE (event_id, member_id)
);
CREATE INDEX ix_attendance_member ON attendance (member_id, event_id);

CREATE TABLE check_in_attempt (
    kind VARCHAR(16) NOT NULL,
    identity_hash VARCHAR(64) NOT NULL,
    window_start TIMESTAMP(6) NOT NULL,
    attempt_count INTEGER NOT NULL,
    CONSTRAINT pk_check_in_attempt PRIMARY KEY (kind, identity_hash)
);

CREATE TABLE attendance_eligibility_snapshot (
    check_in_session_id BIGINT NOT NULL CONSTRAINT fk_attendance_snapshot_session REFERENCES check_in_session (id),
    member_id BIGINT NOT NULL CONSTRAINT fk_attendance_snapshot_member REFERENCES member (id),
    snapshotted_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_attendance_eligibility_snapshot PRIMARY KEY (check_in_session_id, member_id)
);
CREATE INDEX ix_attendance_snapshot_member ON attendance_eligibility_snapshot (member_id, check_in_session_id);

CREATE TABLE notice_poll (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id BIGINT NOT NULL CONSTRAINT uq_notice_poll_notice UNIQUE
        CONSTRAINT fk_notice_poll_notice REFERENCES notice (id),
    question VARCHAR(200) NOT NULL,
    first_option VARCHAR(80) NOT NULL,
    second_option VARCHAR(80) NOT NULL,
    closes_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE notice_poll_vote (
    poll_id BIGINT NOT NULL CONSTRAINT fk_notice_poll_vote_poll REFERENCES notice_poll (id),
    member_id BIGINT NOT NULL CONSTRAINT fk_notice_poll_vote_member REFERENCES member (id),
    choice SMALLINT NOT NULL CONSTRAINT ck_notice_poll_vote_choice CHECK (choice IN (1, 2)),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_notice_poll_vote PRIMARY KEY (poll_id, member_id)
);
