ALTER TABLE member ADD COLUMN google_subject VARCHAR(255);
CREATE UNIQUE INDEX uq_member_google_subject ON member (google_subject) WHERE google_subject IS NOT NULL;

CREATE TABLE member_allowlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    member_type VARCHAR(16) NOT NULL,
    display_name VARCHAR(100),
    created_by_member_id BIGINT NOT NULL REFERENCES member (id),
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE member_allowlist_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_member_id BIGINT NOT NULL REFERENCES member (id),
    email VARCHAR(320) NOT NULL,
    action VARCHAR(16) NOT NULL,
    member_type VARCHAR(16) NOT NULL,
    acted_at TIMESTAMP(6) NOT NULL
);
